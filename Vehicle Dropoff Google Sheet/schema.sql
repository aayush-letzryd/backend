-- ------------------------------------------------------------------------------
-- 1. TABLE DEFINITION: public.sheet_dropoffs (Raw Staging Table)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.sheet_dropoffs (
    dropoff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_row INTEGER UNIQUE,
    return_date DATE NOT NULL,
    return_type VARCHAR(50) NOT NULL,
    driver_id VARCHAR(50),
    driver_name VARCHAR(255),
    driver_type VARCHAR(30) DEFAULT 'Individual',
    vehicle_number VARCHAR(20) NOT NULL,
    city VARCHAR(50) NOT NULL,
    negative_balance NUMERIC(12,2) DEFAULT 0.00,
    sync_status VARCHAR(20) DEFAULT 'SYNCED',
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')
);

