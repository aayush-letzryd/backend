-- ------------------------------------------------------------------------------
-- 3. ZERO-BURN SEQUENCE CTE UPSERT QUERY (JDBC PREPARED STATEMENT FORMAT)
-- ------------------------------------------------------------------------------
-- Root Cause Addressed:
-- Standard INSERT INTO ... ON CONFLICT (source_row) DO UPDATE advances the
-- underlying IDENTITY sequence (nextval) even when a conflict occurs and an
-- UPDATE is performed. Over frequent 1-minute catch-up syncs, millions of
-- sequence IDs are burned without new rows being inserted.
--
-- Architectural Solution:
-- The Zero-Burn CTE isolates the incoming record into an in-memory row.
-- The `upd` CTE attempts to UPDATE an existing record matching source_row.
-- If an update succeeds, the RETURNING clause captures the dropoff_id.
-- The subsequent INSERT statement executes ONLY when NOT EXISTS (SELECT 1 FROM upd).
-- Thus, nextval() is never evaluated during updates, preserving sequence continuity.
--
-- JDBC Parameter Index Mapping:
-- ? 1: source_row       (INTEGER)
-- ? 2: return_date      (DATE, format: 'YYYY-MM-DD')
-- ? 3: return_type      (VARCHAR)
-- ? 4: driver_id        (VARCHAR)
-- ? 5: driver_name      (VARCHAR)
-- ? 6: driver_type      (VARCHAR)
-- ? 7: vehicle_number   (VARCHAR)
-- ? 8: city             (VARCHAR)
-- ? 9: negative_balance (NUMERIC(12,2))
-- ------------------------------------------------------------------------------

