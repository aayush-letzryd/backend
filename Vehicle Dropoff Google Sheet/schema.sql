-- ------------------------------------------------------------------------------
-- 4. OPERATIONAL VERIFICATION & DIAGNOSTIC QUERIES
-- ------------------------------------------------------------------------------

-- 4.1 Sequence State and last_value Inspection
-- Verifies that the underlying identity sequence matches row count without runaway sequence burning.
SELECT 
    sequence_schema,
    sequence_name,
    data_type,
    start_value,
    minimum_value,
    maximum_value,
    increment,
    cycle_option
FROM information_schema.sequences
WHERE sequence_name LIKE 'sheet_dropoffs_dropoff_id_seq%';

SELECT 
    schemaname,
    sequencename,
    last_value,
    is_called,
    log_cnt
FROM pg_sequences
WHERE sequencename = 'sheet_dropoffs_dropoff_id_seq';

-- 4.2 Sequence Gap Detection Query
-- Identifies any holes in the dropoff_id sequence to confirm Zero-Burn CTE operation.
SELECT 
    dropoff_id + 1 AS gap_start,
    next_id - 1 AS gap_end,
    (next_id - dropoff_id - 1) AS gap_size
FROM (
    SELECT 
        dropoff_id, 
        LEAD(dropoff_id) OVER (ORDER BY dropoff_id) AS next_id
    FROM public.sheet_dropoffs
) sub
WHERE next_id > dropoff_id + 1;

-- 4.3 Sequence Gapless Verification Summary
SELECT 
    COUNT(*) AS total_rows,
    MIN(dropoff_id) AS min_id,
    MAX(dropoff_id) AS max_id,
    (MAX(dropoff_id) - MIN(dropoff_id) + 1) AS expected_span,
    (MAX(dropoff_id) - MIN(dropoff_id) + 1) - COUNT(*) AS gap_count,
    CASE 
        WHEN (MAX(dropoff_id) - MIN(dropoff_id) + 1) = COUNT(*) 
        THEN 'PASSED: Perfectly Continuous Gapless Sequence'
        ELSE 'NOTICE: Sequence gaps exist'
    END AS status_check
FROM public.sheet_dropoffs;

-- 4.4 Duplicate Check on source_row
-- Ensures source_row constraint maintains 1:1 mapping with spreadsheet rows.
SELECT 
    source_row, 
    COUNT(*) AS duplicate_count
FROM public.sheet_dropoffs
WHERE source_row IS NOT NULL
GROUP BY source_row
HAVING COUNT(*) > 1;

-- 4.5 Multi-Event Analysis (Same Vehicle, Same Date)
-- Detects vehicle returns occurring multiple times on the same date.
-- In sheet_dropoffs, these are legitimate separate physical events tracked by distinct source_row.
SELECT 
    vehicle_number, 
    return_date, 
    COUNT(*) AS event_count,
    ARRAY_AGG(source_row ORDER BY source_row) AS source_rows,
    ARRAY_AGG(dropoff_id ORDER BY dropoff_id) AS dropoff_ids,
    SUM(negative_balance) AS total_negative_balance
FROM public.sheet_dropoffs
WHERE is_deleted = FALSE
GROUP BY vehicle_number, return_date
HAVING COUNT(*) > 1
ORDER BY event_count DESC, vehicle_number ASC;

-- 4.6 Ingestion Sync Status and Financial Liability Distribution
SELECT 
    sync_status,
    COUNT(*) AS total_records,
    COUNT(DISTINCT vehicle_number) AS unique_vehicles,
    COUNT(DISTINCT driver_id) AS unique_drivers,
    MIN(return_date) AS earliest_return_date,
    MAX(return_date) AS latest_return_date,
    SUM(negative_balance) AS net_negative_balance,
    COUNT(CASE WHEN negative_balance < 0 THEN 1 END) AS negative_balance_rows,
    COUNT(CASE WHEN negative_balance > 0 THEN 1 END) AS positive_balance_anomalies,
    COUNT(CASE WHEN negative_balance = 0 THEN 1 END) AS zero_balance_rows
FROM public.sheet_dropoffs
GROUP BY sync_status;

-- 4.7 City and Return Type Distribution Summary
SELECT 
    city,
    return_type,
    COUNT(*) AS total_dropoffs,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2) AS pct_share
FROM public.sheet_dropoffs
GROUP BY city, return_type
ORDER BY city ASC, total_dropoffs DESC;

-- 4.8 Vehicle Plate Format Hygiene Audit
-- Verifies that stored vehicle numbers strictly adhere to the standard Indian format.
SELECT 
    vehicle_number,
    COUNT(*) AS occurrences
FROM public.sheet_dropoffs
WHERE vehicle_number !~ '^[A-Z]{2}[0-9]{1,2}[A-Z]{0,3}[0-9]{4}$'
GROUP BY vehicle_number;

